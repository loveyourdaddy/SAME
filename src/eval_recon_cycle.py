#!/usr/bin/env python3
"""Reconstruction (A->A) and cycle (A->B->A') errors for SAME.

Retargeting has no ground truth for A->B (the target character never performed the
source motion), so plain error metrics are undefined. These two proxies DO have a
true GT = the original source A (same skeleton), so mpjpe / rot_err are valid:

  1. reconstruction   A -> A        encode src, decode onto the SOURCE skeleton,
                                     compare to the original src.
  2. cycle            A -> B -> A'   encode src, decode onto the TARGET skeleton B
                                     (only B's skeleton is used, not its motion),
                                     re-encode that generated motion, decode back
                                     onto the source skeleton A', compare to src.

Only the SOURCE motions from the pair list are used. For the cycle the target
contributes just its species/skeleton (from the pair's tgt column); the middle
motion on B is generated by the model. Because the decoder emits only the 'out'
representation ([r,q,c]), the intermediate B motion is reconstructed and passed
through motion_2_graph (recomputing p/pv/qv/pprev/c) before re-encoding.

Usage (run per fold: the fold's model on the fold's test pairs):
  cd src
  python eval_recon_cycle.py \
      --model_epoch 260803_cfg_VT_fold0 \
      --data_dir "Trueboness_processed_byVT/processed/" \
      --pairs_txt truebones_vt_groups_fold0_test.txt \
      --out_csv result/260803_cfg_VT_fold0/test/recon_cycle.csv
"""
import argparse
import csv
import os
import sys
import time

import numpy as np

current_dir = os.path.dirname(os.path.abspath(__file__))
if current_dir not in sys.path:
    sys.path.insert(0, current_dir)                       # put src/ on the path

import torch  # noqa: E402
from mypath import DATA_DIR  # noqa: E402
from same.test import (  # noqa: E402
    prepare_model_test, retarget, load_pair_dataset, decode_z_skelgraph, read_pairs,
    scale_motion, _safe_name,
)
from same.mydataset import get_mi_src_tgt_all_graph  # noqa: E402
from conversions.motion_to_graph import motion_2_graph, skel_2_graph  # noqa: E402
from conversions.graph_to_motion import graph_2_skel  # noqa: E402
from fairmotion.data import bvh  # noqa: E402


# ----------------------------- helpers -------------------------------

def motion_pos_rot(m, scale=1.0):
    """fairmotion Motion -> (positions [T,J,3]*scale, local rotations [T,J,3,3])."""
    T = len(m.poses)
    J = m.skel.num_joints()
    pos = np.zeros((T, J, 3), dtype=np.float32)
    rot = np.zeros((T, J, 3, 3), dtype=np.float32)
    for t, pose in enumerate(m.poses):
        for j in range(J):
            pos[t, j] = pose.get_transform(j, local=False)[:3, 3]
            rot[t, j] = np.asarray(pose.data[j])[:3, :3]
    return pos * scale, rot


def mpjpe(a, b):
    T = min(len(a), len(b)); J = min(a.shape[1], b.shape[1])
    return float(np.linalg.norm(a[:T, :J] - b[:T, :J], axis=-1).mean())


def rot_err(a, b):
    T = min(len(a), len(b)); J = min(a.shape[1], b.shape[1])
    d = np.einsum("...ij,...ik->...jk", a[:T, :J], b[:T, :J])
    tr = d[..., 0, 0] + d[..., 1, 1] + d[..., 2, 2]
    return float(np.degrees(np.arccos(np.clip((tr - 1.0) / 2.0, -1.0, 1.0))).mean())


def encode_motion(model, motion):
    """fairmotion Motion -> latent z (recomputes the full pose rep via graph)."""
    g = motion_2_graph(motion).to(device=model.device)
    return model.encoder[0](g)


# ------------------------------- main --------------------------------

def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--model_epoch", type=str, required=True)
    ap.add_argument("--data_dir", type=str, default="Trueboness_processed_byVT/processed/")
    ap.add_argument("--pairs_txt", type=str, nargs="+", required=True,
                    help="pair list file name(s) under data_dir (source column used)")
    ap.add_argument("--device", type=str, default="cuda:0")
    ap.add_argument("--unit_scale", type=float, default=100.0,
                    help="scale positions by this for cm reporting")
    ap.add_argument("--out_csv", type=str, default=None)
    ap.add_argument("--max_pairs", type=int, default=-1)
    ap.add_argument("--no_save", dest="save", action="store_false",
                    help="do NOT save recon/cycle bvh (default: save)")
    ap.set_defaults(save=True)
    ap.add_argument("--save_mid", action="store_true",
                    help="also save the intermediate B motion (source->target)")
    args = ap.parse_args()

    model, cfg, ms_dict = prepare_model_test(args.model_epoch, args.device)
    out_rep = cfg["representation"]["out"]
    data_dir = os.path.join(DATA_DIR, args.data_dir)

    pairs = []
    for pt in args.pairs_txt:
        pairs += read_pairs(os.path.join(data_dir, pt))
    if args.max_pairs > 0:
        pairs = pairs[: args.max_pairs]

    out_csv = args.out_csv or os.path.join(
        os.path.dirname(os.path.abspath(os.path.join(data_dir, "x"))), "recon_cycle.csv")
    os.makedirs(os.path.dirname(os.path.abspath(out_csv)), exist_ok=True)

    # generated bvh go under <test_dir>/{recon,cycle[,cycle_mid]}/
    out_dir = os.path.dirname(os.path.abspath(out_csv))
    recon_dir = os.path.join(out_dir, "recon")
    cycle_dir = os.path.join(out_dir, "cycle")
    mid_dir = os.path.join(out_dir, "cycle_mid")
    if args.save:
        os.makedirs(recon_dir, exist_ok=True)
        os.makedirs(cycle_dir, exist_ok=True)
        if args.save_mid:
            os.makedirs(mid_dir, exist_ok=True)
        print(f"[eval] saving bvh -> {recon_dir} (A->A), {cycle_dir} (A->B->A')")

    print(f"[eval] {len(pairs)} pairs | model={args.model_epoch} | scale={args.unit_scale}")

    rows = []
    recon_done = set()
    recon_mp, recon_ro, cyc_mp, cyc_ro = [], [], [], []

    for idx, (src_rel, tgt_rel) in enumerate(pairs):
        status, msg = "OK", ""
        rec_mpjpe = rec_rot = cyc_mpjpe = cyc_rot = None
        t0 = time.time()
        try:
            pair_ds = load_pair_dataset(data_dir, src_rel, tgt_rel)

            # ---- cycle A -> B -> A' (B = target skeleton only) ----
            (src_b, tgt_b), cn = get_mi_src_tgt_all_graph(
                pair_ds, mi=0, src_ri=0, tgt_ri=1, device=args.device)
            src_gt, _, out_tgt = retarget(model, src_b, tgt_b, ms_dict, out_rep, cn)
            z2 = encode_motion(model, out_tgt)                     # re-encode B motion
            src_skel = graph_2_skel(src_b, 1)[0]
            a_prime, _ = decode_z_skelgraph(model, z2, skel_2_graph(src_skel), ms_dict)
            p_src, r_src = motion_pos_rot(src_gt, args.unit_scale)
            p_cyc, r_cyc = motion_pos_rot(a_prime, args.unit_scale)
            cyc_mpjpe, cyc_rot = mpjpe(p_src, p_cyc), rot_err(r_src, r_cyc)
            cyc_mp.append(cyc_mpjpe); cyc_ro.append(cyc_rot)

            # ---- reconstruction A -> A (once per unique source) ----
            if src_rel not in recon_done:
                (s_b, s_b2), cn2 = get_mi_src_tgt_all_graph(
                    pair_ds, mi=0, src_ri=0, tgt_ri=0, device=args.device)
                s_gt, _, a_recon = retarget(model, s_b, s_b2, ms_dict, out_rep, cn2)
                pg, rg = motion_pos_rot(s_gt, args.unit_scale)
                pr, rr = motion_pos_rot(a_recon, args.unit_scale)
                rec_mpjpe, rec_rot = mpjpe(pg, pr), rot_err(rg, rr)
                recon_mp.append(rec_mpjpe); recon_ro.append(rec_rot)
                recon_done.add(src_rel)

            # ---- save generated bvh (metrics already computed above) ----
            if args.save:
                stem = f"{_safe_name(src_rel)}__TO__{_safe_name(tgt_rel)}"
                try:
                    bvh.save(scale_motion(a_prime, args.unit_scale),
                             os.path.join(cycle_dir, f"{stem}.bvh"))
                    if args.save_mid:
                        bvh.save(scale_motion(out_tgt, args.unit_scale),
                                 os.path.join(mid_dir, f"{stem}.bvh"))
                    if rec_mpjpe is not None:   # recon computed this iter (unique src)
                        bvh.save(scale_motion(a_recon, args.unit_scale),
                                 os.path.join(recon_dir, f"{_safe_name(src_rel)}.bvh"))
                except Exception as se:
                    print(f"    [warn] bvh save failed for {src_rel}->{tgt_rel}: {se!r}")
        except Exception as e:
            import traceback
            status, msg = "FAIL", repr(e)
            traceback.print_exc()
        dt = time.time() - t0

        def _f(v):
            return f"{v:.4f}" if v is not None else "N/A"
        rows.append({"idx": idx, "src_rel": src_rel, "tgt_rel": tgt_rel,
                     "recon_mpjpe": _f(rec_mpjpe), "recon_rot": _f(rec_rot),
                     "cycle_mpjpe": _f(cyc_mpjpe), "cycle_rot": _f(cyc_rot),
                     "status": status, "secs": f"{dt:.2f}"})
        rec_s = f"recon={_f(rec_mpjpe)}cm/{_f(rec_rot)}deg" if rec_mpjpe is not None else "recon=(dup)"
        print(f"  [{idx:04d}] {status}  {src_rel} -> {tgt_rel}  "
              f"cycle={_f(cyc_mpjpe)}cm/{_f(cyc_rot)}deg  {rec_s}")

    # ---- write CSV + summary ----
    fields = ["idx", "src_rel", "tgt_rel", "recon_mpjpe", "recon_rot",
              "cycle_mpjpe", "cycle_rot", "status", "secs"]
    with open(out_csv, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)
        w.writerow({"idx": "MEAN", "src_rel": f"n_src={len(recon_mp)}",
                    "tgt_rel": f"n_cyc={len(cyc_mp)}",
                    "recon_mpjpe": f"{np.mean(recon_mp):.4f}" if recon_mp else "N/A",
                    "recon_rot": f"{np.mean(recon_ro):.4f}" if recon_ro else "N/A",
                    "cycle_mpjpe": f"{np.mean(cyc_mp):.4f}" if cyc_mp else "N/A",
                    "cycle_rot": f"{np.mean(cyc_ro):.4f}" if cyc_ro else "N/A",
                    "status": "", "secs": ""})

    print("\n================ Summary ================")
    print(f"  reconstruction (A->A)  mpjpe={np.mean(recon_mp):.4f} cm   "
          f"rot={np.mean(recon_ro):.4f} deg   (n={len(recon_mp)} unique sources)"
          if recon_mp else "  reconstruction: N/A")
    print(f"  cycle          (A->B->A')  mpjpe={np.mean(cyc_mp):.4f} cm   "
          f"rot={np.mean(cyc_ro):.4f} deg   (n={len(cyc_mp)} pairs)"
          if cyc_mp else "  cycle: N/A")
    print(f"\n[eval] -> {out_csv}")


if __name__ == "__main__":
    main()
